def parse_pair_capture(paths):
    values = {}
    chars = {}
    for path in paths:
        for line in Path(path).read_bytes().split(b"\n"):
            match = re.search(rb"PTPAIR f=(\d) s=(\d+) a=", line)
            if not match:
                continue
            face, size = int(match.group(1)), int(match.group(2))
            if face not in PAIR_FACES or not 1 <= size <= 100:
                raise SystemExit(f"{path}: bad pair face/size {face}/{size}")
            # Widths below one are encoded as a literal space, so a regex that
            # excludes spaces cannot parse these rows.
            payload = line[match.end():]
            target_bytes = len(PAIR_TARGETS)
            if (len(payload) != target_bytes + 3 + len(PAIR_CHARS) or
                    payload[target_bytes:target_bytes + 3] != b" c="):
                raise SystemExit(f"{path}: bad pair/char row width")
            encoded = payload[:target_bytes]
            encoded_chars = payload[target_bytes + 3:]
            values[(face, size)] = [byte - 32 for byte in encoded]
            chars[(face, size)] = [byte - 32 for byte in encoded_chars]
    missing = [(face, size) for face in PAIR_FACES for size in range(1, 101)
               if (face, size) not in values or (face, size) not in chars]
    if missing:
        raise SystemExit(f"missing {len(missing)} pair rows: {missing[:8]}")
    return chars, values


def parse_capture(paths):
    values = {}
    for path in paths:
        for line in Path(path).read_bytes().split(b"\n"):
            match = re.search(rb"CAP f=(\d) s=(\d+) a=", line)
            if not match:
                continue
            encoded = line[match.end():]
            if len(encoded) != len(charset()):
                raise SystemExit(f"{path}: expected {len(charset())} bytes, got {len(encoded)}")
            face, size = int(match.group(1)), int(match.group(2))
            if not (0 <= face < 5 and 1 <= size <= 100):
                raise SystemExit(f"{path}: bad face/size {face}/{size}")
            row = [byte - 32 for byte in encoded]
            if max(row) > 223:
                raise SystemExit(f"{path}: advance does not fit one encoded byte")
            values[(face, size)] = row
    missing = [(face, size) for face in range(5) for size in range(1, 101)
               if (face, size) not in values]
    if missing:
        raise SystemExit(f"missing {len(missing)} face/size rows: {missing[:8]}")
    return values


def fixture_text(values):
    chars = charset()
    lines = [
        "# Generated by tests/live/generate_font_metrics.py from native CAP rows.",
        "# One row per face/size; bytes are decoded as advance = byte - 32.",
        "charset=" + ",".join(f"{cp:04X}" for cp in chars),
        "rows=" + str(len(values)),
    ]
    for (face, size), row in sorted(values.items()):
        encoded = "".join(f"{value:02x}" for value in row)
        lines.append(f"ADV f={face} s={size} {encoded}")
    return "\n".join(lines) + "\n"


def pair_fixture_text(chars, values):
    targets = ["".join(f"{ord(ch):04X}" for ch in target) for target in PAIR_TARGETS]
    lines = [
        "# Generated by tests/live/generate_font_metrics.py from native PTPAIR rows.",
        "# Values are native TextBounds.X bytes with 32 subtracted.",
        "pairs=" + ",".join(targets),
        "chars=" + ",".join(f"{ord(ch):04X}" for ch in PAIR_CHARS),
        "rows=" + str(len(values)),
    ]
    for (face, size), row in sorted(values.items()):
        lines.append(f"PAIR f={face} s={size} " + "".join(f"{v:02x}" for v in row))
    for (face, size), row in sorted(chars.items()):
        lines.append(f"CHAR f={face} s={size} " + "".join(f"{v:02x}" for v in row))
    return "\n".join(lines) + "\n"


def read_pair_fixture(path):
    pairs = None
    chars = None
    values = {}
    char_values = {}
    for line in Path(path).read_text().splitlines():
        if line.startswith("pairs="):
            pairs = []
            for item in line.split("=", 1)[1].split(","):
                if len(item) != 8:
                    raise SystemExit(f"bad pair key: {item}")
                pairs.append((int(item[:4], 16), int(item[4:], 16)))
        elif line.startswith("chars="):
            chars = [int(item, 16) for item in line.split("=", 1)[1].split(",")]
        elif line.startswith("CHAR "):
            match = re.fullmatch(r"CHAR f=(\d) s=(\d+) ([0-9a-f]+)", line)
            if not match:
                raise SystemExit(f"bad char fixture row: {line[:80]}")
            row = [int(match.group(3)[i:i + 2], 16)
                   for i in range(0, len(match.group(3)), 2)]
            char_values[(int(match.group(1)), int(match.group(2)))] = row
        elif line.startswith("PAIR "):
            match = re.fullmatch(r"PAIR f=(\d) s=(\d+) ([0-9a-f]+)", line)
            if not match:
                raise SystemExit(f"bad pair fixture row: {line[:80]}")
            row = [int(match.group(3)[i:i + 2], 16)
                   for i in range(0, len(match.group(3)), 2)]
            values[(int(match.group(1)), int(match.group(2)))] = row
    if pairs is None or len(pairs) != len(PAIR_TARGETS):
        raise SystemExit("pair fixture targets do not match generator targets")
    if [f"{a:04X}{b:04X}" for a, b in pairs] != [
            "".join(f"{ord(ch):04X}" for ch in target) for target in PAIR_TARGETS]:
        raise SystemExit("pair fixture order does not match generator targets")
    if chars is None or len(chars) != len(PAIR_CHARS):
        raise SystemExit("pair fixture chars do not match generator chars")
    if chars != [ord(ch) for ch in PAIR_CHARS]:
        raise SystemExit("pair fixture char order does not match generator chars")
    if (len(values) != len(PAIR_FACES) * 100 or
            len(char_values) != len(PAIR_FACES) * 100):
        raise SystemExit("pair fixture does not contain 100 rows per face")
    return pairs, chars, values, char_values


def emit_pair_inc(pairs, chars, values, char_values):
    char_index = {cp: index for index, cp in enumerate(chars)}
    for first, second in pairs:
        if first not in char_index or second not in char_index:
            raise SystemExit(f"pair {first:04X} {second:04X} is outside the pair charset")
    lines = [
        "// Generated by tests/live/generate_font_metrics.py.  Do not hand-edit.",
        "// Native quantized GPOS adjustments for adjacent non-ASCII pairs, derived",
        "// from captured native pair widths and standalone advances.",
        "",
    ]
    for face in PAIR_FACES:
        kept = []
        for pair_index, (first, second) in enumerate(pairs):
            adjustments = []
            for size in range(1, 101):
                base = (char_values[(face, size)][char_index[first]] +
                        char_values[(face, size)][char_index[second]])
                adjustments.append(values[(face, size)][pair_index] - base)
            if any(adjustments):
                kept.append(((first << 16) | second, adjustments))
        kept.sort(key=lambda item: item[0])
        if not kept:
            continue
        lines.append(
            f"const UnicodeKernPair kUnicodeKern{face}[{len(kept)}] = {{")
        for key, adjustments in kept:
            body = ",".join(str(value) for value in adjustments)
            lines.append(f"    {{0x{key:08X}, {{{body}}}}},")
        lines.append("};")
        lines.append("")
    if not any(f"kUnicodeKern{face}" in "\n".join(lines) for face in PAIR_FACES):
        raise SystemExit("native pair capture produced no adjustments")
    return "\n".join(lines) + "\n"


def read_fixture(path):
    text = Path(path).read_text()
    chars = None
    values = {}
    for line in text.splitlines():
        if line.startswith("charset="):
            chars = [int(item, 16) for item in line.split("=", 1)[1].split(",")]
        elif line.startswith("ADV "):
            match = re.fullmatch(r"ADV f=(\d) s=(\d+) ([0-9a-f]+)", line)
            if not match:
                raise SystemExit(f"bad fixture row: {line[:80]}")
            row = [int(match.group(3)[i:i + 2], 16) for i in range(0, len(match.group(3)), 2)]
            values[(int(match.group(1)), int(match.group(2)))] = row
    if chars is None or len(chars) != len(charset()):
        raise SystemExit("fixture charset does not match generator charset")
    if len(values) != 500:
        raise SystemExit(f"expected 500 fixture rows, got {len(values)}")
    return chars, values


def emit_inc(chars, values):
    lines = [
        "// Generated by tests/live/generate_font_metrics.py.  Do not hand-edit.",
        "// Native standalone TextBounds.X for each codepoint, indexed by size-1.",
        "",
    ]
    for face in range(5):
        lines.append(f"const UnicodeAdvance kUnicode{face}[{len(chars)}] = {{")
        for index, cp in enumerate(chars):
            advances = [values[(face, size)][index] for size in range(1, 101)]
            body = ",".join(str(value) for value in advances)
            lines.append(f"    {{0x{cp:04X}, {{{body}}}}},")
        lines.append("};")
        lines.append("")
    lines.append("const UnicodeFaceData kUnicodeFaces[kFaceCount] = {")
    for face in range(5):
        lines.append(f"    {{kUnicode{face}, {len(chars)}}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "command", choices=["probe", "fixture", "emit",
                            "pairprobe", "pairfixture", "pairemit"])
    parser.add_argument("--out", required=True)
    parser.add_argument("logs", nargs="*")
    parser.add_argument("--fixture")
    parser.add_argument("--advance-fixture")
    args = parser.parse_args()

    if args.command == "probe":
        Path(args.out).write_text(probe_text())
    elif args.command == "fixture":
        if not args.logs:
            parser.error("fixture needs one or more native CAP logs")
        Path(args.out).write_text(fixture_text(parse_capture(args.logs)))
    elif args.command == "emit":
        if not args.fixture:
            parser.error("emit needs --fixture")
        chars, values = read_fixture(args.fixture)
        Path(args.out).write_text(emit_inc(chars, values))
    elif args.command == "pairprobe":
        Path(args.out).write_text(pair_probe_text())
    elif args.command == "pairfixture":
        if not args.logs:
            parser.error("pairfixture needs one or more native PTPAIR logs")
        chars, values = parse_pair_capture(args.logs)
        Path(args.out).write_text(pair_fixture_text(chars, values))
    else:
        if not args.fixture:
            parser.error("pairemit needs --fixture")
        pairs, chars, values, char_values = read_pair_fixture(args.fixture)
        Path(args.out).write_text(
            emit_pair_inc(pairs, chars, values, char_values))


if __name__ == "__main__":
    main()
