FACE_NAMES = ["Legacy", "Arial", "ArialBold", "SourceSans", "SourceSansBold"]

# Native applies non-zero non-ASCII pair adjustments only on the SourceSans
# faces for this charset; the probe still reads every authored pair so a new
# native build can change that without editing the table by hand.
PAIR_FACES = [3, 4]
PAIR_TARGETS = ["Vé", "fé", "o”", "rö", "rø", "s”", "é?", "Łó"]
PAIR_CHARS = sorted({ch for target in PAIR_TARGETS for ch in target})


def charset():
    values = sorted({cp for first, last in RANGES for cp in range(first, last + 1)} | set(EXTRA))
    if values != sorted(set(values)):
        raise ValueError("charset is not sorted")
    return values


def lua_escape(cp):
    return "".join("\\%d" % byte for byte in chr(cp).encode("utf-8"))


