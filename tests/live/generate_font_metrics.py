#!/usr/bin/env python3
"""Generate and compile the native font-metric captures.

The native client is the authority.  `probe` writes a Luau capture script;
run it with Xecutor/Rum, then `fixture` turns the CAP lines into a portable
text fixture, and `emit` writes the C++ table included by
rbx_runtime/src/gui/gui_font_metrics.cpp.

The source characters are Latin-1, Latin Extended-A, combining marks,
punctuation, currency, arrows, box drawing, geometric/common UI symbols and
U+FFFD (the native replacement glyph used for uncaptured codepoints).  Every
codepoint is measured as a standalone TextLabel at TextSize 1..100, so the
table contains native advances rather than a font approximation.

The `pairprobe`/`pairfixture`/`pairemit` commands do the same for the adjacent
non-ASCII GPOS pairs that native advances alone cannot express.  Pair rows are
raw native TextBounds widths; the adjustment is derived from the captured
standalone advances when compiling, not hand-entered.
"""
