#!/usr/bin/env python3
"""gen_proptable.py — native prop table (tools/proptable.tsv) + solver wire-shape
overrides (tools/proptable_overrides.tsv) -> client/src/proptable.inc.

The .tsv is a live register dump of the replicator's runtime prop table
(10146 entries == prop_bound+1): entry byte[9] is the value-tag number in
snapshot numbering (== v57[1] == the byte sub_340A3E4 dispatches on;
verified per-prop via breakpoints on sub_3404858/0x3404AFB).

The numbers are the client's STORAGE tags. Where live wire traffic proves
a different wire shape (server 0.742 newer than traced client 2.739 —
version skew), the override wins for parsing; see FINDINGS.md "Recv v3".
Prefix flag (Content/asset tag 33+61 shapes in 0x03 values): shipped
per-prop proven value, else True for 33/61 (native-faithful: the 0x03
call always passes flag=1) and False elsewhere (flag-ignored tags).

The generated file is checked in (precedent: gen_instances.py). Regenerate:
  python3 tools/gen_proptable.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "tools", "proptable.tsv")
OVERRIDES = os.path.join(ROOT, "tools", "proptable_overrides.tsv")
OUT = os.path.join(ROOT, "client", "src", "proptable.inc")


def load_tsv(path):
    rows = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            prop, tag = line.split()[:2]
            rows[int(prop)] = int(tag)
    return rows


def main():
    native = load_tsv(TSV)
    n = max(native) + 1
    assert min(native) == 0 and len(native) == n, "table must be dense 0..N"
    assert n == 10146, f"expected 10146 entries, got {n}"
    overrides = {}  # prop -> (wire_tag, prefix)
    with open(OVERRIDES) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            p, wt, pfx = line.split()[:3]
            overrides[int(p)] = (int(wt), int(pfx))
    tags = []
    prefs = []
    for i in range(n):
        if i in overrides:
            wt, pfx = overrides[i]
        else:
            wt = native[i]
            pfx = 1 if wt in (33, 61) else 0
        assert 0 <= wt <= 70 and wt not in (4, 5, 45), f"bad tag {wt}"
        tags.append(wt)
        prefs.append(pfx)

    def blob(vals):
        lines = []
        for i in range(0, len(vals), 24):
            lines.append("    " + ", ".join(str(v) for v in vals[i:i + 24]) + ",")
        return "\n".join(lines)

    body = (
        "// proptable.inc — DO NOT EDIT. Generated by tools/gen_proptable.py\n"
        "// from tools/proptable.tsv (live register dump, 10146 entries) +\n"
        "// tools/proptable_overrides.tsv (solver-proven wire shapes).\n"
        "// tags[]: wire value tag per prop id (index == prop network id).\n"
        "// prefix[]: Content/asset prefix shape flag per prop (0x03 values).\n"
        "static const int kPropTagCount = %d;\n"
        "static const uint8_t kPropTags[] = {\n%s\n};\n"
        "static const uint8_t kPropPrefix[] = {\n%s\n};\n"
    ) % (n, blob(tags), blob(prefs))
    with open(OUT, "w") as f:
        f.write(body)
    print(f"wrote {OUT}: {n} props, {len(overrides)} overrides")


if __name__ == "__main__":
    main()
